from dataclasses import dataclass, field

import numpy as np
from scipy.interpolate import CubicHermiteSpline


@dataclass(frozen=True)
class Consumer:
    mho: float = 0.005      # probability that an employed consumer becomes unemployed, for good
    beta: float = 1 / 1.10  # discount factor: a time preference rate of 0.10
    R: float = 1.03         # interest factor
    G: float = 1.0          # growth factor of wages
    rho: float = 2.0        # relative risk aversion

    @property
    def G_hat(self):  # wage growth for a consumer who stays employed
        return self.G / (1 - self.mho)

    @property
    def R_norm(self):  # the interest factor relative to that growth
        return self.R / self.G_hat

    @property
    def thorn(self):  # the absolute patience factor
        return (self.R * self.beta) ** (1 / self.rho)

    @property
    def kappa(self):  # the perfect foresight MPC, and the unemployed consumer's
        return 1 - self.thorn / self.R

    @property
    def beth(self):  # the discount factor of the problem in ratios to income
        return self.R_norm * self.beta * self.G_hat ** (1 - self.rho)

    @property
    def h(self):  # human wealth relative to income
        return 1 / (1 - self.G / self.R)


def u2(c, rho):  # u''(c) for CRRA utility, and its next two derivatives
    return -rho * c ** (-rho - 1)


def u3(c, rho):
    return rho * (rho + 1) * c ** (-rho - 2)


def u4(c, rho):
    return -rho * (rho + 1) * (rho + 2) * c ** (-rho - 3)


@dataclass(frozen=True)
class Solution:
    consumer: Consumer
    Pi: float          # consumption of the employed relative to the unemployed, at the target
    m_targ: float
    c_targ: float
    mpc_targ: float
    mpc_targ_1: float  # the MPC's first derivative at the target
    mpc_targ_2: float  # and its second
    mpc_0: float       # the MPC's limit as m goes to 0
    arm: CubicHermiteSpline = field(repr=False)  # through the points reverse shooting finds

    def c(self, m):
        """Consumption of an employed consumer: the stable arm."""
        return self.arm(self.on_arm(m))

    def mpc(self, m):
        return self.arm(self.on_arm(m), 1)

    def on_arm(self, m):
        if np.max(m) > self.arm.x[-1]:  # beyond the last point reverse shooting found
            raise ValueError(f"c is computed only up to m = {self.arm.x[-1]:.1f}; beyond it, use HARK's TractableConsumerType")
        return m

    def c_locus(self, m):
        """Where consumption does not change: c = m zeta / (1 + zeta), zeta = R_norm kappa Pi."""
        zeta = self.consumer.R_norm * self.consumer.kappa * self.Pi
        return m * (zeta / (1.0 + zeta))

    def m_locus(self, m):
        """Where m does not change: c = 1 / R_norm + (1 - 1 / R_norm) m."""
        R_norm = self.consumer.R_norm
        return 1 / R_norm + (1.0 - 1 / R_norm) * m


def previous_point(e, m_next, c_next, mpc_next):
    """m, c and the MPC a period earlier, for a consumer who stays employed."""
    c_now = (
        e.G_hat * (e.beta * e.R) ** (-1.0 / e.rho) * c_next
        * (1 + e.mho * ((c_next / (e.kappa * (m_next - 1.0))) ** e.rho - 1.0)) ** (-1.0 / e.rho)
    )
    m_now = (m_next - 1.0) / e.R_norm + c_now
    c_unemployed_next = e.kappa * (m_now - c_now) * e.R_norm
    natural = e.beth * e.R_norm * (1.0 / u2(c_now, e.rho)) * (
        (1.0 - e.mho) * u2(c_next, e.rho) * mpc_next + e.mho * u2(c_unemployed_next, e.rho) * e.kappa
    )
    return m_now, c_now, natural / (natural + 1)


def solve(e, m_top=16.0):
    """The consumption function of an employed consumer, up to m_top times target m."""
    if e.thorn / e.R >= 1 or e.thorn / e.G_hat >= 1:
        raise ValueError("the consumer must be return impatient and growth impatient")

    # The target.
    Pi = (1 + ((e.thorn / e.G_hat) ** (-e.rho) - 1.0) / e.mho) ** (1 / e.rho)
    zeta = e.R_norm * e.kappa * Pi
    m_targ = 1.0 + (e.R / (e.G_hat + zeta * e.G_hat - e.R))
    c_targ = (1.0 - 1 / e.R_norm) * m_targ + 1 / e.R_norm
    c_unemployed = (m_targ - c_targ) * e.R_norm * e.kappa  # next period, for a consumer who loses the job

    # The MPC at the target: the root in (0, 1) of the quadratic.
    natural_e = e.beth * e.R_norm * (1.0 - e.mho)
    natural_u = e.beth * e.R_norm * e.mho * e.kappa * Pi ** (e.rho + 1.0)
    linear = 1.0 + natural_u - natural_e
    root = np.sqrt(linear**2.0 + 4.0 * natural_e * natural_u)
    k = 2.0 * natural_u / (linear + root) if linear >= 0.0 else (root - linear) / (2.0 * natural_e)

    # Its first and second derivatives, from equations linear in each.
    p, q, b, R, rho, c, cu, kU = 1 - e.mho, e.mho, e.beth, e.R_norm, e.rho, c_targ, c_unemployed, e.kappa
    k1 = (b * R**2 * (1 - k) ** 2 * (p * k**2 * u3(c, rho) + q * kU**2 * u3(cu, rho)) - k**2 * u3(c, rho)) / (
        u2(c, rho) + b * R * (p * k * u2(c, rho) + q * kU * u2(cu, rho)) - b * R**2 * (1 - k) ** 2 * p * u2(c, rho)
    )
    rest = 3 * k * k1 * u3(c, rho) + k**3 * u4(c, rho) - b * (
        -3 * p * (1 - k) * k1**2 * R**2 * u2(c, rho)
        - 3 * p * (1 - k) * k**2 * k1 * R**2 * u3(c, rho)
        + 3 * p * (1 - k) ** 3 * k * k1 * R**3 * u3(c, rho)
        - 3 * q * kU**2 * (1 - k) * k1 * R**2 * u3(cu, rho)
        + p * (1 - k) ** 3 * k**3 * R**3 * u4(c, rho)
        + q * kU**3 * (1 - k) ** 3 * R**3 * u4(cu, rho)
    )
    k2 = -rest / (u2(c, rho) + b * (p * k * R * u2(c, rho) - p * (1 - k) ** 3 * R**3 * u2(c, rho) + q * kU * R * u2(cu, rho)))

    # The MPC's limit as m goes to 0.
    mpc_0 = e.kappa / (e.kappa + e.thorn / e.R * e.mho ** (1.0 / e.rho))

    # The stable arm, from a step to either side of the target.
    d = 0.1 * m_targ
    below = [(m_targ - d, c_targ - d * k + 0.5 * d**2 * k1 - d**3 / 6 * k2, k - d * k1 + 0.5 * d**2 * k2)]
    above = [(m_targ + d, c_targ + d * k + 0.5 * d**2 * k1 + d**3 / 6 * k2, k + d * k1 + 0.5 * d**2 * k2)]
    while below[-1][0] > 1.0:
        below.append(previous_point(e, *below[-1]))
    while above[-1][0] < m_top * m_targ:
        above.append(previous_point(e, *above[-1]))
    m, c_arm, mpc = np.array([(0.0, 0.0, mpc_0), *below[::-1], (m_targ, c_targ, k), *above]).T
    return Solution(e, Pi, m_targ, c_targ, k, k1, k2, mpc_0, CubicHermiteSpline(m, c_arm, mpc, extrapolate=False))
