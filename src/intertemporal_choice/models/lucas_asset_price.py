from dataclasses import dataclass, replace

import numpy as np
from scipy.interpolate import CubicSpline


@dataclass(frozen=True)
class Economy:
    rho: float = 3.0     # relative risk aversion
    theta: float = 0.04  # time preference rate
    sigma: float = 0.1   # standard deviation of the shock z to log dividends
    tau: float = 0.0     # persistence of log dividends: 0 for IID, 1 for a random walk
    gamma: float = 0.0   # growth: in a random walk, dividends grow by the factor e**gamma on average

    @property
    def beta(self):      # the time preference factor
        return 1 / (1 + self.theta)


def log_strip(e, n, x):
    """The log of the value of the dividend n periods ahead relative to today's,
    log E_t[(d_{t+n}/d_t)**(1-rho)], when today's log dividend is x."""
    S = n if e.tau == 1 else (1 - e.tau**n) / (1 - e.tau)  # the sum of tau**k for k < n
    Q = n if e.tau == 1 else (1 - e.tau ** (2 * n)) / (1 - e.tau**2)  # the sum of tau**(2k)
    a = 1 - e.rho
    return a * ((e.tau**n - 1) * x + e.gamma * S) - e.sigma**2 / 2 * a * S + e.sigma**2 / 2 * a**2 * Q


def pd_series(e, d, horizon=100_000):
    """The price-dividend ratio of Lucas's tree when the dividend is d: the sum of beta**n times
    the strips (added in logs, since a strip alone can be too large for the computer)."""
    if e.tau == 1:  # a geometric series: y + y**2 + ... = y/(1-y), infinite unless y < 1
        y = np.exp(np.log(e.beta) + log_strip(e, 1, np.log(d)))
        return y / (1 - y) if y < 1 else np.inf
    n = np.arange(1, horizon + 1)
    with np.errstate(over="ignore"):
        terms = np.exp(n * np.log(e.beta) + log_strip(e, n, np.log(d)))
    if not terms[-1] < 1e-12 * terms.sum():
        raise ValueError(f"the series has not converged in {horizon:,} terms: raise the horizon")
    return terms.sum()


z_std, weights = np.polynomial.hermite_e.hermegauss(15)  # values of a standard normal, and their
weights = weights / weights.sum()                       # probabilities, for the averages


def aggregate(e, x, x_next, own):
    """Lucas's tree: its dividend is consumption, so it grows as consumption does."""
    return np.exp(x_next - x)


def next_x(e, x):
    """Tomorrow's log dividend at each of the fifteen values of the shock z (the last axis)."""
    z = -e.sigma**2 / 2 + e.sigma * z_std
    return e.tau * np.asarray(x, float)[..., None] + e.gamma + z


def discounted_growth(e, growth, x):
    """Tomorrow's log dividend, and beta * (c_{t+1}/c_t)**(-rho) * d_{t+1}/d_t at each value of the
    shock, averaged over any shock of the tree's own (a second average, which changes nothing for
    Lucas's tree)."""
    x_next = next_x(e, x)
    x = np.asarray(x, float)[..., None]
    sdf = e.beta * np.exp(-e.rho * (x_next - x))
    own = sum(w * growth(e, x, x_next, s) for s, w in zip(z_std, weights))
    return x_next, sdf * own


def interpolate(grid, values, x):
    """values, given on the grid, at x: a cubic spline between grid points, and straight lines
    beyond the ends."""
    spline = CubicSpline(grid, values)
    inside = spline(np.clip(x, grid[0], grid[-1]))
    below = values[0] + spline(grid[0], 1) * (x - grid[0])     # spline(point, 1) is its slope there
    above = values[-1] + spline(grid[-1], 1) * (x - grid[-1])
    return np.where(x < grid[0], below, np.where(x > grid[-1], above, inside))


def solve(e, growth=aggregate, points=101, tolerance=1e-11):
    """The price-dividend ratio of a tree whose dividend grows by `growth`, as a function of the
    aggregate dividend: the fixed point of the pricing equation."""
    spread = e.sigma / np.sqrt(1 - e.tau**2) if e.tau < 1 else e.sigma    # the spread of x,
    center = (e.gamma - e.sigma**2 / 2) / (1 - e.tau) if e.tau < 1 else 0  # and its mean
    grid = center + spread * np.linspace(-6, 6, points)
    x_next, m = discounted_growth(e, growth, grid)

    ratio = m @ weights  # the first round, with tomorrow's ratio taken to be zero
    for _ in range(100_000):
        new = (m * (1 + np.exp(interpolate(grid, np.log(ratio), x_next)))) @ weights
        if not np.isfinite(new).all() or np.median(new) > 1e9:
            raise ValueError("the ratio grows without limit: there is no finite price")
        if np.max(np.abs(new / ratio - 1)) < tolerance:
            break
        ratio = new
    else:
        raise RuntimeError("the ratio has not converged in 100,000 rounds")

    def ratio_at(d):
        x_next, m = discounted_growth(e, growth, np.log(d))
        return (m * (1 + np.exp(interpolate(grid, np.log(new), x_next)))) @ weights

    return ratio_at


def riskless(e, d):
    """The riskless return factor when the aggregate dividend is d."""
    x = np.log(np.asarray(d, float))
    return 1 / ((e.beta * np.exp(-e.rho * (next_x(e, x) - x[..., None]))) @ weights)


def expected_return(e, ratio, d, growth=aggregate):
    """A tree's expected return factor when the aggregate dividend is d, given its price-dividend
    ratio as a function of the aggregate dividend (what solve returns)."""
    x = np.log(np.asarray(d, float))
    x_next = next_x(e, x)
    dividend_growth = sum(w * growth(e, x[..., None], x_next, s) for s, w in zip(z_std, weights))
    return (dividend_growth * (1 + ratio(np.exp(x_next)))) @ weights / ratio(d)


def small_tree(b=1.0, own=0.0, growth_rate=None):
    """A small tree's dividend growth: exposure b to the economy's shock, a shock of its own with
    standard deviation `own`, and expected growth by the factor e**growth_rate (the economy's gamma
    if growth_rate is None)."""

    def growth(e, x, x_next, eta):
        g = e.gamma if growth_rate is None else growth_rate
        shock = x_next - (e.tau * x + e.gamma - e.sigma**2 / 2)  # the economy's shock, mean zero
        return np.exp(g - (b**2 * e.sigma**2 + own**2) / 2 + b * shock + own * eta)

    return growth
