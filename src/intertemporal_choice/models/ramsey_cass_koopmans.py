from dataclasses import dataclass, replace

import numpy as np
from scipy.integrate import solve_ivp


@dataclass(frozen=True)
class Economy:
    rho: float = 2.0     # relative risk aversion
    alpha: float = 0.3   # capital's share of output
    theta: float = 0.02  # time preference rate
    xi: float = 0.01     # population growth rate
    delta: float = 0.08  # depreciation rate
    phi: float = 0.03    # labor productivity growth rate

    @property
    def dilution(self):  # capital per efficiency unit shrinks at this rate when none is added
        return self.xi + self.phi + self.delta

    @property
    def nu(self):        # the time preference rate that discounts utility per efficiency unit
        return self.theta - (1 - self.rho) * self.phi


def kdot(e, k, c):
    return k**e.alpha - c - e.dilution * k


def cdot(e, k, c):
    return c * (e.alpha * k ** (e.alpha - 1) - e.theta - e.xi - e.delta - e.rho * e.phi) / e.rho


def kdot_zero(e, k):
    """The kdot = 0 locus: the consumption that keeps k where it is."""
    return k**e.alpha - e.dilution * k


def steady_state(e):
    """(k, c) where neither moves: the cdot/c = 0 line meets the kdot = 0 locus."""
    k = (e.alpha / (e.theta + e.xi + e.delta + e.rho * e.phi)) ** (1 / (1 - e.alpha))
    return k, kdot_zero(e, k)


def golden_rule(e):
    """The k at the top of the kdot = 0 locus, where steady-state consumption is highest."""
    return (e.alpha / e.dilution) ** (1 / (1 - e.alpha))


def saddle_slope(e):
    """dc/dk along the saddle path at the steady state."""
    k, c = steady_state(e)
    jacobian = np.array([
        [e.alpha * k ** (e.alpha - 1) - e.dilution, -1.0],               # d kdot/dk, d kdot/dc
        [c * e.alpha * (e.alpha - 1) * k ** (e.alpha - 2) / e.rho, 0.0],  # d cdot/dk, d cdot/dc
    ])
    values, vectors = np.linalg.eig(jacobian)
    stable = vectors[:, np.argmin(values)]
    return stable[1] / stable[0]


def saddle_path(e, k_low, k_high):
    """The saddle path's consumption as a function of k on [k_low, k_high]."""
    k_ss, c_ss = steady_state(e)
    slope = saddle_slope(e)
    step = 1e-5 * k_ss
    branches = []
    for end, side in ((k_low, -1), (k_high, 1)):
        start = k_ss + side * step
        branches.append(solve_ivp(lambda k, c: cdot(e, k, c) / kdot(e, k, c), (start, end), [c_ss + slope * side * step],
                                  rtol=1e-10, atol=1e-12, dense_output=True).sol)
    below, above = branches

    def c(k):
        k = np.asarray(k, float)
        near = c_ss + slope * (k - k_ss)  # within a step of the steady state, the straight line between the branches
        return np.where(k < k_ss - step, below(np.minimum(k, k_ss - step))[0],
                        np.where(k > k_ss + step, above(np.maximum(k, k_ss + step))[0], near))

    return c


def path(e, k0, c0, k_max, T=400):
    """The (k, c) path from (k0, c0) until time T, or until k nearly reaches zero or passes k_max."""
    def exhausted(t, y):
        return y[0] - 0.01
    def past(t, y):
        return y[0] - k_max
    exhausted.terminal = past.terminal = True
    solution = solve_ivp(lambda t, y: [kdot(e, *y), cdot(e, *y)], (0, T), [k0, c0], events=[exhausted, past],
                         rtol=1e-9, max_step=0.5)
    return solution.y
