"""Write each chapter's model, the cells of its notebook tagged `export`, into a module of the package.

A chapter's notebook shows the economics: the reader sees every line of the code that solves the
model. Other notebooks, a problem set's answer key above all, should compute with that same code
rather than a copy of it. So the cells that define the model carry the tag `export`, and this tool
writes them, in order, into `src/intertemporal_choice/models/<name>.py`. The name is the chapter's
folder in snake_case, so nobody picks it and two chapters can't share one: LucasAssetPrice's model
is `models.lucas_asset_price`, beside the drawing module `intertemporal_choice.lucas`.

    from intertemporal_choice import models
    model = models.lucas_asset_price
    model.solve(model.Economy())(1.0)

The notebook stays the only source. A generated module says so at its top and is never edited by
hand; CI fails when one differs from what its notebook's cells would write. The modules are
committed, so installing the package needs no build step.

An exported cell may only import, define functions and classes, and assign names: no figures, no
printing, nothing that takes long. Importing a model must be cheap and must not draw. The tool
refuses any other statement, and any name the module uses but never defines (one defined only in
a cell that isn't exported, which would fail only when called). Its check imports each module in
a fresh, isolated Python and fails if that loads matplotlib's pyplot or takes more than
IMPORT_BUDGET seconds.

`models/__init__.py` is generated too. It imports a model only when it is first used, so a model
that needs a heavy package (HARK, say) costs nothing to a notebook that uses another.

A new chapter's model: tag its cells `export`, add the notebook to MODELS, and run this tool.

Usage: uv run python code/export_models.py [--check | --self-test]
"""

import ast
import builtins
import json
import logging
import re
import subprocess
import symtable
import sys
import tempfile
from pathlib import Path

logging.basicConfig(level=logging.INFO, format="%(message)s", force=True)
log = logging.getLogger(__name__)

ROOT = Path(__file__).resolve().parent.parent
MODELS_DIR = ROOT / "src" / "intertemporal_choice" / "models"
# The chapter notebooks whose cells tagged `export` make a model.
MODELS = [
    "content/asset_pricing/LucasAssetPrice/LucasAssetPrice.ipynb",
]
ALLOWED = (ast.Import, ast.ImportFrom, ast.FunctionDef, ast.ClassDef, ast.Assign, ast.AnnAssign)
IMPORT_BUDGET = 2.0  # seconds: importing a model must not compute anything that takes long
GENERATED = "Do not edit this file"  # in every generated file; only those are ever replaced or removed


def module_name(path: str) -> str:
    """The model's name: its chapter's folder in snake_case (LucasAssetPrice: lucas_asset_price)."""
    folder = Path(path).parent.name.replace("-", "_")
    return re.sub(r"(?<=[a-z0-9])(?=[A-Z])|(?<=[A-Z])(?=[A-Z][a-z])", "_", folder).lower()


def undefined_names(text: str, filename: str) -> list[str]:
    """The names the module's functions and classes use but nothing in the module defines."""
    top = symtable.symtable(text, filename, "exec")
    bound = {s.get_name() for s in top.get_symbols() if s.is_assigned() or s.is_imported()} | set(dir(builtins))
    missing = set()

    def walk(table):
        for child in table.get_children():
            missing.update(s.get_name() for s in child.get_symbols()
                           if s.is_referenced() and s.is_global() and s.get_name() not in bound)
            walk(child)

    walk(top)
    return sorted(missing)


def exported_cells(notebook: dict) -> list[str]:
    """The sources of the code cells tagged `export`, in order."""
    return [
        "".join(cell["source"]).strip("\n")
        for cell in notebook["cells"]
        if cell["cell_type"] == "code" and "export" in (cell.get("metadata") or {}).get("tags", [])
    ]


def refusals(source: str) -> list[str]:
    """What in an exported cell is not an import, a definition or an assignment."""
    if any(line.lstrip().startswith(("%", "!")) for line in source.splitlines()):
        return ["an IPython command"]
    found = []
    for node in ast.parse(source).body:
        docstring = isinstance(node, ast.Expr) and isinstance(node.value, ast.Constant) and isinstance(node.value.value, str)
        if not (isinstance(node, ALLOWED) or docstring):
            found.append(f"line {node.lineno}: {ast.get_source_segment(source, node).splitlines()[0]}")
    return found


def module_text(name: str, path: str, notebook: dict) -> str:
    """The module the notebook's exported cells make."""
    cells = exported_cells(notebook)
    if not cells:
        raise ValueError(f"{path} has no cell tagged export")
    for number, source in enumerate(cells):
        if problems := refusals(source):
            raise ValueError(f"{path}, exported cell {number}: not an import, definition or assignment: {problems}")
    title = next((line.split(":", 1)[1].strip().strip('"').removeprefix("Figures: ")
                  for line in "".join(notebook["cells"][0]["source"]).splitlines() if line.startswith("title:")), name)
    header = (
        f'"""{title}: the model of the chapter\'s notebook, for other notebooks to import:\n\n'
        "    from intertemporal_choice import models\n"
        f"    model = models.{name}\n\n"
        f"Written by code/export_models.py from the cells tagged `export` in\n{path}.\n"
        f"{GENERATED}: edit those cells and run the tool again.\n"
        '"""\n'
    )
    text = header + "\n" + "\n\n\n".join(cells) + "\n"
    if missing := undefined_names(text, f"{name}.py"):
        raise ValueError(f"{path}: the exported cells use {missing}, which no exported cell defines")
    return text


def init_text() -> str:
    names = ", ".join(f'"{name}"' for name in sorted(module_name(path) for path in MODELS))
    return (
        f'"""The chapters\' models, written from their notebooks by code/export_models.py. {GENERATED}.\n\n'
        "`models.<name>` imports a model when it is first used, so each costs only the notebooks that use it.\n"
        '"""\n\n'
        "import importlib\n\n"
        f"__all__ = [{names}]\n\n\n"
        "def __getattr__(name):\n"
        "    if name in __all__:\n"
        '        return importlib.import_module(f".{name}", __name__)\n'
        '    raise AttributeError(f"module {__name__!r} has no attribute {name!r}")\n'
    )


def wanted(root: Path = ROOT) -> dict[Path, str]:
    """Every generated file, and what it should hold."""
    files = {MODELS_DIR / "__init__.py": init_text()}
    for path in MODELS:
        notebook = json.loads((root / path).read_text(encoding="utf-8"))
        files[MODELS_DIR / f"{module_name(path)}.py"] = module_text(module_name(path), path, notebook)
    return files


def imports_lightly(name: str) -> str | None:
    """None if the model imports in a fresh, isolated Python (-I, so nothing in the current folder
    can shadow a module) quickly and without loading pyplot; otherwise what went wrong."""
    probe = (
        "import sys, time\n"
        "start = time.perf_counter()\n"
        "from intertemporal_choice import models\n"
        f"models.{name}\n"
        "took = time.perf_counter() - start\n"
        "assert 'matplotlib.pyplot' not in sys.modules, 'it loads matplotlib.pyplot'\n"
        f"assert took < {IMPORT_BUDGET}, f'it takes {{took:.1f}} s, over the budget of {IMPORT_BUDGET} s'\n"
    )
    done = subprocess.run([sys.executable, "-I", "-c", probe], capture_output=True, text=True, cwd=ROOT)
    return None if done.returncode == 0 else (done.stderr.strip().splitlines() or ["failed"])[-1]


def check() -> bool:
    ok = True
    for path, text in wanted().items():
        if not path.is_file() or path.read_text(encoding="utf-8") != text:
            log.error(f"{path.relative_to(ROOT)} is not what its notebook's exported cells write: run code/export_models.py")
            ok = False
    extra = {p for p in MODELS_DIR.glob("*.py")} - set(wanted())
    for path in sorted(extra):
        log.error(f"{path.relative_to(ROOT)} is not written from any notebook in MODELS")
        ok = False
    for name in (module_name(path) for path in MODELS):
        if problem := imports_lightly(name):
            log.error(f"models.{name} does not import cleanly and without figures: {problem}")
            ok = False
    if ok:
        log.info(f"{len(MODELS)} model(s) match their notebooks and import without drawing")
    return ok


def write() -> None:
    MODELS_DIR.mkdir(exist_ok=True)
    files = wanted()
    for path, text in files.items():
        if not path.is_file() or path.read_text(encoding="utf-8") != text:
            path.write_text(text, encoding="utf-8")
            log.info(f"wrote {path.relative_to(ROOT)}")
    for path in sorted(set(MODELS_DIR.glob("*.py")) - set(files)):  # a model renamed or dropped
        if GENERATED in path.read_text(encoding="utf-8"):
            path.unlink()
            log.info(f"removed {path.relative_to(ROOT)}, which no notebook in MODELS writes any more")


def self_test() -> bool:
    cell = lambda source, tags=(): {"cell_type": "code", "metadata": {"tags": list(tags)}, "source": source}
    notebook = {"cells": [
        {"cell_type": "markdown", "metadata": {}, "source": '---\ntitle: "Figures: A Model"\n---'},
        cell("import numpy as np\n", ["export"]),
        cell("import matplotlib.pyplot as plt\n"),
        cell('RATE = 0.04\n\n\ndef double(x):\n    """Twice x."""\n    return 2 * x\n', ["export"]),
        cell("plt.plot([0, 1])\n"),
    ]}
    failures = []
    names = {"content/a/LucasAssetPrice/X.ipynb": "lucas_asset_price", "content/a/Portfolio-CRRA/X.ipynb": "portfolio_crra",
             "content/a/OLGModel/X.ipynb": "olg_model", "content/a/Fisher2Period/X.ipynb": "fisher2_period"}
    for path, name in names.items():
        if module_name(path) != name:
            failures.append(f"the model of {path} should be {name}, not {module_name(path)}")
    text = module_text("a", "content/a/A.ipynb", notebook)
    namespace = {}
    exec(compile(text, "a.py", "exec"), namespace)
    if namespace["double"](3) != 6 or "plt" in namespace or not text.startswith('"""A Model: the model'):
        failures.append("the exported cells, and only those, should make the module, under the notebook's title")
    notebook["cells"].insert(3, cell("WEIGHTS = [0.5, 0.5]\n"))  # defined in a cell that isn't exported...
    notebook["cells"].append(cell("def average(xs):\n    return sum(w * x for w, x in zip(WEIGHTS, xs))\n", ["export"]))
    try:  # ...and used by one that is: the module would import, and fail only when average is called
        module_text("a", "content/a/A.ipynb", notebook)
        failures.append("an exported function using a name no exported cell defines was not refused")
    except ValueError:
        pass
    del notebook["cells"][3], notebook["cells"][-1]
    for bad in ("plt.plot([0, 1])\n", "print(RATE)\n", "for i in range(3):\n    pass\n", "%matplotlib inline\n"):
        notebook["cells"].append(cell(bad, ["export"]))
        try:
            module_text("a", "content/a/A.ipynb", notebook)
            failures.append(f"an exported cell holding {bad.strip()!r} was not refused")
        except (ValueError, SyntaxError):
            pass
        notebook["cells"].pop()
    with tempfile.TemporaryDirectory() as folder:
        package = Path(folder) / "pkg"
        package.mkdir()
        (package / "__init__.py").write_text("")
        (package / "models").mkdir()
        (package / "models" / "__init__.py").write_text(init_text())
        (package / "models" / "lucas_asset_price.py").write_text("LOADED = True\n")
        probe = ("import sys\nfrom pkg import models\nassert 'pkg.models.lucas_asset_price' not in sys.modules\n"
                 "assert models.lucas_asset_price.LOADED\n")
        done = subprocess.run([sys.executable, "-c", probe], capture_output=True, text=True, cwd=folder)
        if done.returncode != 0:
            failures.append(f"models/__init__.py should import a model when it is first used: {done.stderr.strip()}")
    for failure in failures:
        log.error(f"export_models self-test: {failure}")
    if not failures:
        log.info("export_models self-test: ok")
    return not failures


if __name__ == "__main__":
    if "--self-test" in sys.argv:
        sys.exit(0 if self_test() else 1)
    if "--check" in sys.argv:
        sys.exit(0 if check() else 1)
    write()
